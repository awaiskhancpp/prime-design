const GOOGLEBOT = 'Mozilla/5.0 (compatible; Googlebot/2.1; +http://www.google.com/bot.html)'
const res = await fetch('https://primedesignandbuild.com/', { headers: { 'User-Agent': GOOGLEBOT } })
console.log('status', res.status)
const html = await res.text()
console.log('length', html.length)
const vids = [...html.matchAll(/<video[^>]*>/g)].map((m) => m[0])
console.log('video tags:', vids.length)
vids.slice(0, 6).forEach((v) => console.log('  ', v))
const posters = [...html.matchAll(/poster="[^"]*"/g)].map((m) => m[0])
console.log('poster attrs:', posters.length)
posters.slice(0, 8).forEach((p) => console.log('  ', p))
const srcs = [...html.matchAll(/tagmediaspace\.b-cdn\.net[^"']*\.mp4/g)].map((m) => m[0])
console.log('cdn mp4 refs:', srcs.length)
srcs.slice(0, 8).forEach((s) => console.log('  ', s))
